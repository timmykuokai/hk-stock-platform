/** 取得熱門池（去重） */
export function popularList() {
  const seen = new Set();
  const out = [];
  for (const [code, meta] of POPULAR) {
    const c = code.padStart(5, '0');
    if (seen.has(c)) continue;
    seen.add(c);
    out.push({ code: c, ...meta });
  }
  return out;
}

